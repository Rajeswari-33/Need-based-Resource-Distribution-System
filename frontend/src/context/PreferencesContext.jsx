export function PreferencesProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('setu-language') || 'en')
  const [theme, setTheme] = useState(() => localStorage.getItem('setu-theme') || 'light')
  const [accentColor, setAccentColor] = useState(() => {
    const savedColor = localStorage.getItem('setu-accent-color')
    return isHexColor(savedColor) ? savedColor : DEFAULT_ACCENT_COLOR
  })

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dataset.language = language
    document.title = language === 'ta'
      ? 'சேது — தேவையடிப்படையிலான வளப் பகிர்வு'
      : 'Setu — Need-Based Resource Distribution'
    localStorage.setItem('setu-language', language)
  }, [language])

  useEffect(() => {
    document.documentElement.dataset.theme = theme
    localStorage.setItem('setu-theme', theme)
  }, [theme])

  useEffect(() => {
    applyAccentColor(accentColor)
    localStorage.setItem('setu-accent-color', accentColor)
  }, [accentColor])

  const t = (text) => {
    if (language !== 'ta' || typeof text !== 'string') return text
    if (translations[text]) return translations[text]
    const match = translationPatterns.find(([pattern]) => pattern.test(text))
    return match ? text.replace(match[0], match[1]) : text
  }

  const itemName = (englishName, tamilName) => (
    language === 'ta' ? tamilName?.trim() || t(englishName) : englishName
  )

  return (
    <PreferencesContext.Provider value={{ language, setLanguage, theme, setTheme, accentColor, setAccentColor, t, itemName }}>
      {children}
    </PreferencesContext.Provider>
  )
}

export function usePreferences() {
  const context = useContext(PreferencesContext)
  if (!context) throw new Error('usePreferences must be used within PreferencesProvider')
  return context
}