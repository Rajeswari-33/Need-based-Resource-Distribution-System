function isHexColor(value) {
  return /^#[\da-f]{6}$/i.test(value || '')
}

function hexToRgb(hex) {
  return hex.slice(1).match(/.{2}/g).map((channel) => Number.parseInt(channel, 16))
}

function blendRgb(rgb, target, amount) {
  return rgb.map((channel, index) => Math.round(channel + (target[index] - channel) * amount).toString()).join(' ')
}

function applyAccentColor(color) {
  const root = document.documentElement
  const rgb = hexToRgb(color)
  const luminance = rgb.map((channel) => {
    const value = channel / 255
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4
  }).reduce((sum, channel, index) => sum + channel * [0.2126, 0.7152, 0.0722][index], 0)
  const channels = rgb.join(' ')

  root.dataset.customPalette = 'true'
  root.style.setProperty('--palette-rgb', channels)
  root.style.setProperty('--palette-dark', blendRgb(rgb, [0, 0, 0], 0.24))
  root.style.setProperty('--palette-contrast', luminance > 0.179 ? '20 27 46' : '255 255 255')
  root.style.setProperty('--marigold', channels)
  root.style.setProperty('--marigold-dark', blendRgb(rgb, [0, 0, 0], 0.2))
  root.style.setProperty('--marigold-light', blendRgb(rgb, [255, 255, 255], 0.48))
  root.style.setProperty('--banyan', channels)
  root.style.setProperty('--banyan-dark', blendRgb(rgb, [0, 0, 0], 0.3))
  root.style.setProperty('--banyan-light', blendRgb(rgb, [255, 255, 255], 0.3))
}

